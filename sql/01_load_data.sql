/*=============================================================================
  01_load_data.sql — Load Parquet files from internal stages into tables.
  Requires: 00_setup.sql executed, Parquet files PUT to stages.
  Critical: FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE) — without
  USE_LOGICAL_TYPE, pandas timestamps corrupt to year 55670000+.
=============================================================================*/

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE AGENT_EVAL_DEMO_WH;
USE DATABASE AGENT_EVAL_DEMO;

-- Internal stages for data loading (one per schema for clarity)
CREATE STAGE IF NOT EXISTS FULFILLMENT_INTELLIGENCE.DATA_STAGE;
CREATE STAGE IF NOT EXISTS INVENTORY_INTELLIGENCE.DATA_STAGE;
CREATE STAGE IF NOT EXISTS LABOR_INTELLIGENCE.DATA_STAGE;
CREATE STAGE IF NOT EXISTS SHIPPING_INTELLIGENCE.DATA_STAGE;

-- File format
CREATE OR REPLACE FILE FORMAT FULFILLMENT_INTELLIGENCE.PARQUET_FMT
  TYPE = PARQUET
  USE_LOGICAL_TYPE = TRUE;

-- ============ FULFILLMENT_INTELLIGENCE ============

CREATE OR REPLACE TABLE FULFILLMENT_INTELLIGENCE.ORDERS (
    ORDER_ID VARCHAR(20) NOT NULL,
    TENANT_ID VARCHAR(10) NOT NULL,
    ORDER_DATE TIMESTAMP_NTZ,
    SHIP_BY_DATE TIMESTAMP_NTZ,
    PROMISED_DELIVERY_DATE TIMESTAMP_NTZ,
    WAREHOUSE_ID VARCHAR(20),
    PRIORITY VARCHAR(20),
    TOTAL_LINES INTEGER,
    LINES_FILLED INTEGER,
    STATUS VARCHAR(20),
    CHANNEL VARCHAR(20)
);

CREATE OR REPLACE TABLE FULFILLMENT_INTELLIGENCE.ORDER_LINES (
    ORDER_LINE_ID VARCHAR(20) NOT NULL,
    ORDER_ID VARCHAR(20) NOT NULL,
    TENANT_ID VARCHAR(10) NOT NULL,
    SKU VARCHAR(20),
    QTY_ORDERED_EACHES INTEGER,
    QTY_SHIPPED_EACHES INTEGER,
    QTY_CARTONS INTEGER,
    UNIT_PRICE NUMBER(10,2),
    LINE_STATUS VARCHAR(20),
    WAVE_ID VARCHAR(40)
);

CREATE OR REPLACE TABLE FULFILLMENT_INTELLIGENCE.WAVES (
    WAVE_ID VARCHAR(40) NOT NULL,
    WAREHOUSE_ID VARCHAR(20),
    WAVE_DATE DATE,
    CUTOFF_TIME VARCHAR(10),
    STATUS VARCHAR(20),
    TOTAL_ORDERS INTEGER,
    TOTAL_LINES INTEGER,
    TOTAL_UNITS INTEGER
);

CREATE OR REPLACE TABLE FULFILLMENT_INTELLIGENCE.EXCEPTIONS (
    EXCEPTION_ID VARCHAR(20) NOT NULL,
    ORDER_ID VARCHAR(20),
    TENANT_ID VARCHAR(10),
    EXCEPTION_TYPE VARCHAR(30),
    EXCEPTION_DATE TIMESTAMP_NTZ,
    RESOLUTION VARCHAR(20),
    WAREHOUSE_ID VARCHAR(20),
    NOTES VARCHAR(200)
);

CREATE OR REPLACE TABLE FULFILLMENT_INTELLIGENCE.FISCAL_CALENDAR_445 (
    CALENDAR_DATE DATE NOT NULL,
    FISCAL_YEAR INTEGER,
    FISCAL_QUARTER INTEGER,
    FISCAL_PERIOD INTEGER,
    FISCAL_WEEK INTEGER,
    FISCAL_WEEK_IN_PERIOD INTEGER,
    CALENDAR_YEAR INTEGER,
    CALENDAR_MONTH INTEGER,
    CALENDAR_WEEK INTEGER,
    DAY_OF_WEEK VARCHAR(15)
);

-- ============ INVENTORY_INTELLIGENCE ============

CREATE OR REPLACE TABLE INVENTORY_INTELLIGENCE.ITEM_MASTER (
    SKU VARCHAR(20) NOT NULL,
    DESCRIPTION VARCHAR(200),
    CATEGORY VARCHAR(50),
    SUBCATEGORY VARCHAR(50),
    UNIT_WEIGHT_LB NUMBER(8,2),
    EACHES_PER_CARTON INTEGER,
    UNIT_COST NUMBER(10,2),
    HAZMAT_FLAG VARCHAR(1),
    TEMPERATURE_SENSITIVE VARCHAR(1),
    CREATED_DATE TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE INVENTORY_INTELLIGENCE.ON_HAND (
    SKU VARCHAR(20),
    WAREHOUSE_ID VARCHAR(20),
    TENANT_ID VARCHAR(10),
    QTY_ON_HAND_EACHES INTEGER,
    QTY_ALLOCATED INTEGER,
    QTY_AVAILABLE INTEGER,
    LAST_COUNT_DATE TIMESTAMP_NTZ,
    LOCATION_ID VARCHAR(30)
);

CREATE OR REPLACE TABLE INVENTORY_INTELLIGENCE.MOVEMENTS (
    MOVEMENT_ID VARCHAR(20) NOT NULL,
    SKU VARCHAR(20),
    TENANT_ID VARCHAR(10),
    WAREHOUSE_ID VARCHAR(20),
    MOVEMENT_TYPE VARCHAR(20),
    QTY_EACHES INTEGER,
    MOVEMENT_DATE TIMESTAMP_NTZ,
    REFERENCE_ID VARCHAR(20)
);

-- ============ LABOR_INTELLIGENCE ============

CREATE OR REPLACE TABLE LABOR_INTELLIGENCE.PICK_TASKS (
    PICK_TASK_ID VARCHAR(20) NOT NULL,
    ORDER_LINE_ID VARCHAR(20),
    ORDER_ID VARCHAR(20),
    TENANT_ID VARCHAR(10),
    SKU VARCHAR(20),
    QTY_PICKED INTEGER,
    PICKER_ID VARCHAR(20),
    PICK_START_TS TIMESTAMP_NTZ,
    PICK_DURATION_SEC NUMBER(8,1),
    ZONE VARCHAR(20),
    WAVE_ID VARCHAR(40)
);

CREATE OR REPLACE TABLE LABOR_INTELLIGENCE.LABOR_STANDARDS (
    ZONE VARCHAR(20),
    PICK_METHOD VARCHAR(20),
    STANDARD_PICKS_PER_HOUR INTEGER,
    STANDARD_UNITS_PER_HOUR INTEGER,
    EFFECTIVE_DATE DATE
);

-- ============ SHIPPING_INTELLIGENCE ============

CREATE OR REPLACE TABLE SHIPPING_INTELLIGENCE.SHIPMENTS (
    SHIPMENT_ID VARCHAR(20) NOT NULL,
    ORDER_ID VARCHAR(20),
    TENANT_ID VARCHAR(10),
    CARRIER VARCHAR(10),
    ZONE INTEGER,
    WEIGHT_BREAK VARCHAR(10),
    TOTAL_WEIGHT_LB NUMBER(8,2),
    PACKAGE_COUNT INTEGER,
    SHIP_DATE TIMESTAMP_NTZ,
    CARRIER_FIRST_SCAN_TS TIMESTAMP_NTZ,
    SHIP_BY_DATE TIMESTAMP_NTZ,
    PROMISED_DELIVERY_DATE TIMESTAMP_NTZ,
    WAREHOUSE_ID VARCHAR(20),
    TRACKING_NUMBER VARCHAR(30)
);

CREATE OR REPLACE TABLE SHIPPING_INTELLIGENCE.CARRIER_SCANS (
    SCAN_ID VARCHAR(20) NOT NULL,
    SHIPMENT_ID VARCHAR(20),
    TENANT_ID VARCHAR(10),
    SCAN_TYPE VARCHAR(30),
    SCAN_TIMESTAMP TIMESTAMP_NTZ,
    LOCATION VARCHAR(20),
    CARRIER VARCHAR(10)
);

CREATE OR REPLACE TABLE SHIPPING_INTELLIGENCE.ZONE_RATE_CARDS (
    CARRIER VARCHAR(10),
    ZONE INTEGER,
    WEIGHT_BREAK VARCHAR(10),
    RATE_PER_PACKAGE NUMBER(8,2),
    FUEL_SURCHARGE_PCT NUMBER(5,1),
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE
);

-- ============ COPY INTO from stages ============
-- Files are loaded via: snow stage put data/*.parquet @<schema>.DATA_STAGE

COPY INTO FULFILLMENT_INTELLIGENCE.ORDERS
  FROM @FULFILLMENT_INTELLIGENCE.DATA_STAGE/orders.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO FULFILLMENT_INTELLIGENCE.ORDER_LINES
  FROM @FULFILLMENT_INTELLIGENCE.DATA_STAGE/order_lines.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO FULFILLMENT_INTELLIGENCE.WAVES
  FROM @FULFILLMENT_INTELLIGENCE.DATA_STAGE/waves.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO FULFILLMENT_INTELLIGENCE.EXCEPTIONS
  FROM @FULFILLMENT_INTELLIGENCE.DATA_STAGE/exceptions.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO FULFILLMENT_INTELLIGENCE.FISCAL_CALENDAR_445
  FROM @FULFILLMENT_INTELLIGENCE.DATA_STAGE/fiscal_calendar_445.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO INVENTORY_INTELLIGENCE.ITEM_MASTER
  FROM @INVENTORY_INTELLIGENCE.DATA_STAGE/item_master.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO INVENTORY_INTELLIGENCE.ON_HAND
  FROM @INVENTORY_INTELLIGENCE.DATA_STAGE/on_hand.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO INVENTORY_INTELLIGENCE.MOVEMENTS
  FROM @INVENTORY_INTELLIGENCE.DATA_STAGE/movements.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO LABOR_INTELLIGENCE.PICK_TASKS
  FROM @LABOR_INTELLIGENCE.DATA_STAGE/pick_tasks.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO LABOR_INTELLIGENCE.LABOR_STANDARDS
  FROM @LABOR_INTELLIGENCE.DATA_STAGE/labor_standards.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO SHIPPING_INTELLIGENCE.SHIPMENTS
  FROM @SHIPPING_INTELLIGENCE.DATA_STAGE/shipments.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO SHIPPING_INTELLIGENCE.CARRIER_SCANS
  FROM @SHIPPING_INTELLIGENCE.DATA_STAGE/carrier_scans.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

COPY INTO SHIPPING_INTELLIGENCE.ZONE_RATE_CARDS
  FROM @SHIPPING_INTELLIGENCE.DATA_STAGE/zone_rate_cards.parquet
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE)
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Verify row counts. NOTE: the alias must not be `rows` -- that is a reserved
-- word in Snowflake and makes this statement fail with 001003, which exits the
-- whole script non-zero even though every COPY INTO above succeeded.
SELECT 'ORDERS' AS tbl, COUNT(*) AS row_count FROM FULFILLMENT_INTELLIGENCE.ORDERS
UNION ALL SELECT 'ORDER_LINES', COUNT(*) FROM FULFILLMENT_INTELLIGENCE.ORDER_LINES
UNION ALL SELECT 'WAVES', COUNT(*) FROM FULFILLMENT_INTELLIGENCE.WAVES
UNION ALL SELECT 'EXCEPTIONS', COUNT(*) FROM FULFILLMENT_INTELLIGENCE.EXCEPTIONS
UNION ALL SELECT 'FISCAL_CALENDAR', COUNT(*) FROM FULFILLMENT_INTELLIGENCE.FISCAL_CALENDAR_445
UNION ALL SELECT 'ITEM_MASTER', COUNT(*) FROM INVENTORY_INTELLIGENCE.ITEM_MASTER
UNION ALL SELECT 'ON_HAND', COUNT(*) FROM INVENTORY_INTELLIGENCE.ON_HAND
UNION ALL SELECT 'MOVEMENTS', COUNT(*) FROM INVENTORY_INTELLIGENCE.MOVEMENTS
UNION ALL SELECT 'PICK_TASKS', COUNT(*) FROM LABOR_INTELLIGENCE.PICK_TASKS
UNION ALL SELECT 'LABOR_STANDARDS', COUNT(*) FROM LABOR_INTELLIGENCE.LABOR_STANDARDS
UNION ALL SELECT 'SHIPMENTS', COUNT(*) FROM SHIPPING_INTELLIGENCE.SHIPMENTS
UNION ALL SELECT 'CARRIER_SCANS', COUNT(*) FROM SHIPPING_INTELLIGENCE.CARRIER_SCANS
UNION ALL SELECT 'ZONE_RATE_CARDS', COUNT(*) FROM SHIPPING_INTELLIGENCE.ZONE_RATE_CARDS;
