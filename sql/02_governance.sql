/*=============================================================================
  02_governance.sql — Multi-tenant row access policy + demo tenant roles

  IMPORTANT: Row Access Policies require Snowflake ENTERPRISE EDITION or above.
  https://docs.snowflake.com/en/user-guide/security-row-intro
  On a Standard Edition account this script will fail. Skip it: every other
  part of the demo runs without it, and only the tenant-isolation eval
  (08_tenant_isolation_eval.sql) depends on the policy existing.

  This script creates:
    1. A tenant-to-role mapping table
    2. A row access policy referencing that mapping
    3. Policy applied to all 8 tenant-scoped tables
    4. Two demo tenant roles (TENANT_ALDERWOOD, TENANT_BELLWEATHER) for isolation proof

  Connection: my_snowflake_connection (ACCOUNTADMIN on the primary demo account)
=============================================================================*/

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE AGENT_EVAL_DEMO_WH;
USE DATABASE AGENT_EVAL_DEMO;

-- ============================================================================
-- 1. Tenant-role mapping table
-- ============================================================================
CREATE SCHEMA IF NOT EXISTS OPS;

CREATE OR REPLACE TABLE OPS.TENANT_ROLE_MAPPING (
    TENANT_ID   VARCHAR(10) NOT NULL,
    TENANT_NAME VARCHAR(100),
    ROLE_NAME   VARCHAR(100) NOT NULL,
    CONSTRAINT PK_TENANT_ROLE PRIMARY KEY (TENANT_ID, ROLE_NAME)
);

INSERT INTO OPS.TENANT_ROLE_MAPPING (TENANT_ID, TENANT_NAME, ROLE_NAME)
VALUES
    ('T001', 'Alderwood Logistics',  'TENANT_ALDERWOOD'),
    ('T002', 'Bellweather Freight',    'TENANT_BELLWEATHER'),
    ('T003', 'Cobalt Apparel',   'TENANT_COBALT'),
    ('T004', 'Dunmore Distribution',   'TENANT_DUNMORE'),
    ('T005', 'Everline Medical',  'TENANT_EVERLINE'),
    ('T006', 'Foxglove Foods',   'TENANT_FOXGLOVE');

-- ============================================================================
-- 2. Row access policy
--    Logic: ACCOUNTADMIN bypasses (sees all rows). A tenant role sees only its
--    own rows. Any other role sees nothing (fail-closed).
-- ============================================================================
CREATE OR REPLACE ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY
  AS (tenant_id_val VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() = 'ACCOUNTADMIN'
    OR EXISTS (
        SELECT 1
        FROM AGENT_EVAL_DEMO.OPS.TENANT_ROLE_MAPPING m
        WHERE m.TENANT_ID = tenant_id_val
          AND m.ROLE_NAME = CURRENT_ROLE()
    );

-- ============================================================================
-- 3. Apply policy to all tenant-scoped tables
--    NOTE: If re-running, you must first DROP the policy from each table:
--      ALTER TABLE <table> DROP ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY;
--    Snowflake has no "ADD ... IF NOT EXISTS" for row access policies.
--    CREATE OR REPLACE above handles the policy definition itself.
-- ============================================================================

-- FULFILLMENT_INTELLIGENCE
ALTER TABLE FULFILLMENT_INTELLIGENCE.ORDERS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

ALTER TABLE FULFILLMENT_INTELLIGENCE.ORDER_LINES
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

ALTER TABLE FULFILLMENT_INTELLIGENCE.EXCEPTIONS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

-- INVENTORY_INTELLIGENCE
ALTER TABLE INVENTORY_INTELLIGENCE.ON_HAND
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

ALTER TABLE INVENTORY_INTELLIGENCE.MOVEMENTS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

-- LABOR_INTELLIGENCE
ALTER TABLE LABOR_INTELLIGENCE.PICK_TASKS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

-- SHIPPING_INTELLIGENCE
ALTER TABLE SHIPPING_INTELLIGENCE.SHIPMENTS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

ALTER TABLE SHIPPING_INTELLIGENCE.CARRIER_SCANS
  ADD ROW ACCESS POLICY OPS.TENANT_ISOLATION_POLICY ON (TENANT_ID);

-- ============================================================================
-- 4. Demo tenant roles + grants
-- ============================================================================
CREATE ROLE IF NOT EXISTS TENANT_ALDERWOOD
  COMMENT = 'Demo tenant role: Alderwood Logistics (T001)';
CREATE ROLE IF NOT EXISTS TENANT_BELLWEATHER
  COMMENT = 'Demo tenant role: Bellweather Freight (T002)';

-- Grant warehouse usage
GRANT USAGE ON WAREHOUSE AGENT_EVAL_DEMO_WH TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON WAREHOUSE AGENT_EVAL_DEMO_WH TO ROLE TENANT_BELLWEATHER;

-- Grant database + schema usage
GRANT USAGE ON DATABASE AGENT_EVAL_DEMO TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON DATABASE AGENT_EVAL_DEMO TO ROLE TENANT_BELLWEATHER;

GRANT USAGE ON SCHEMA FULFILLMENT_INTELLIGENCE TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON SCHEMA FULFILLMENT_INTELLIGENCE TO ROLE TENANT_BELLWEATHER;
GRANT USAGE ON SCHEMA INVENTORY_INTELLIGENCE TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON SCHEMA INVENTORY_INTELLIGENCE TO ROLE TENANT_BELLWEATHER;
GRANT USAGE ON SCHEMA LABOR_INTELLIGENCE TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON SCHEMA LABOR_INTELLIGENCE TO ROLE TENANT_BELLWEATHER;
GRANT USAGE ON SCHEMA SHIPPING_INTELLIGENCE TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON SCHEMA SHIPPING_INTELLIGENCE TO ROLE TENANT_BELLWEATHER;
GRANT USAGE ON SCHEMA OPS TO ROLE TENANT_ALDERWOOD;
GRANT USAGE ON SCHEMA OPS TO ROLE TENANT_BELLWEATHER;

-- Grant SELECT on all tenant-scoped tables
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.ORDERS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.ORDERS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.ORDER_LINES TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.ORDER_LINES TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.EXCEPTIONS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.EXCEPTIONS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.ON_HAND TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.ON_HAND TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.MOVEMENTS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.MOVEMENTS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE LABOR_INTELLIGENCE.PICK_TASKS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE LABOR_INTELLIGENCE.PICK_TASKS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.SHIPMENTS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.SHIPMENTS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.CARRIER_SCANS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.CARRIER_SCANS TO ROLE TENANT_BELLWEATHER;

-- Grant SELECT on the mapping table (policy reads it)
GRANT SELECT ON TABLE OPS.TENANT_ROLE_MAPPING TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE OPS.TENANT_ROLE_MAPPING TO ROLE TENANT_BELLWEATHER;

-- Grant SELECT on reference tables (no RAP, shared across tenants)
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.WAVES TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.WAVES TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.FISCAL_CALENDAR_445 TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE FULFILLMENT_INTELLIGENCE.FISCAL_CALENDAR_445 TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.ITEM_MASTER TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE INVENTORY_INTELLIGENCE.ITEM_MASTER TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE LABOR_INTELLIGENCE.LABOR_STANDARDS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE LABOR_INTELLIGENCE.LABOR_STANDARDS TO ROLE TENANT_BELLWEATHER;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.ZONE_RATE_CARDS TO ROLE TENANT_ALDERWOOD;
GRANT SELECT ON TABLE SHIPPING_INTELLIGENCE.ZONE_RATE_CARDS TO ROLE TENANT_BELLWEATHER;

-- Allow current user to assume tenant roles for demo
GRANT ROLE TENANT_ALDERWOOD TO ROLE ACCOUNTADMIN;
GRANT ROLE TENANT_BELLWEATHER TO ROLE ACCOUNTADMIN;

-- ============================================================================
-- 5. Verify isolation — same query, two roles, disjoint results
-- ============================================================================

-- As ACCOUNTADMIN (sees all):
SELECT 'ACCOUNTADMIN' AS executing_role, TENANT_ID, COUNT(*) AS order_count
FROM FULFILLMENT_INTELLIGENCE.ORDERS
GROUP BY TENANT_ID ORDER BY TENANT_ID;

-- As TENANT_ALDERWOOD (should see only T001):
USE ROLE TENANT_ALDERWOOD;
USE WAREHOUSE AGENT_EVAL_DEMO_WH;
USE DATABASE AGENT_EVAL_DEMO;
SELECT 'TENANT_ALDERWOOD' AS executing_role, TENANT_ID, COUNT(*) AS order_count
FROM FULFILLMENT_INTELLIGENCE.ORDERS
GROUP BY TENANT_ID ORDER BY TENANT_ID;

-- As TENANT_BELLWEATHER (should see only T002):
USE ROLE TENANT_BELLWEATHER;
USE WAREHOUSE AGENT_EVAL_DEMO_WH;
USE DATABASE AGENT_EVAL_DEMO;
SELECT 'TENANT_BELLWEATHER' AS executing_role, TENANT_ID, COUNT(*) AS order_count
FROM FULFILLMENT_INTELLIGENCE.ORDERS
GROUP BY TENANT_ID ORDER BY TENANT_ID;

-- Return to ACCOUNTADMIN
USE ROLE ACCOUNTADMIN;
SELECT 'Governance setup complete — RAP applied to 8 tables, 2 demo tenant roles created' AS status;
